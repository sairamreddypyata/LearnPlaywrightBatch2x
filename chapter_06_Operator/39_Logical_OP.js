let a = true;
let b = false;

console.log(a || b); // true //OR Gate: The output is true (1) if at least one of its inputs is true
console.log(a && b); // false // AND Gate: The output is true (1) only if all of its inputs are true.
console.log(!a); // false // NOT Gate: The output is the inverse of the input. 
// If the input is true (1), the output is false (0), and vice versa.

